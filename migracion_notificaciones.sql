-- Un registro por teléfono: su token de Firebase y de quién es.
-- Si el mismo teléfono inicia sesión con otra cuenta, el token pasa a esa
-- cuenta (por eso el token es único).
create table if not exists dispositivos (
  id          bigint generated by default as identity primary key,
  usuario_id  bigint not null references usuarios(id) on delete cascade,
  token       text not null unique,
  plataforma  text,
  actualizado timestamptz not null default now()
);

create index if not exists dispositivos_usuario_idx on dispositivos (usuario_id);

-- El backend valida la identidad con JWT; permitimos acceso vía anon key.
alter table dispositivos enable row level security;

drop policy if exists "dispositivos_select" on dispositivos;
create policy "dispositivos_select" on dispositivos for select using (true);

drop policy if exists "dispositivos_insert" on dispositivos;
create policy "dispositivos_insert" on dispositivos for insert with check (true);

drop policy if exists "dispositivos_update" on dispositivos;
create policy "dispositivos_update" on dispositivos for update using (true) with check (true);

drop policy if exists "dispositivos_delete" on dispositivos;
create policy "dispositivos_delete" on dispositivos for delete using (true);
